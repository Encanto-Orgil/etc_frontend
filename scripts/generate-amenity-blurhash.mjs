/**
 * Generates blurhash + blurDataURL placeholders for home amenities images.
 * Run: node scripts/generate-amenity-blurhash.mjs
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { encode, decode } from "blurhash";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const publicDir = path.join(__dirname, "../public");
const outFile = path.join(__dirname, "../lib/amenityBlurHashes.ts");

const AMENITY_IMAGE_PATHS = [
  "/images/renders/render-18.jpg",
  "/images/renders/render-25.jpg",
  "/images/renders/render-15.jpg",
  "/images/renders/render-12.jpg",
  "/images/mall/mall-12.jpg",
  "/images/mall/mall-5.jpg",
  "/images/mall/mall-1.jpg",
  "/images/drone/drone-2.jpg",
  "/images/renders/render-31.jpg",
  "/images/renders/render-3.jpg",
];

async function encodeBlurHash(imagePath) {
  const { data, info } = await sharp(imagePath)
    .rotate()
    .raw()
    .ensureAlpha()
    .resize(32, 32, { fit: "inside" })
    .toBuffer({ resolveWithObject: true });

  return encode(new Uint8ClampedArray(data), info.width, info.height, 4, 4);
}

async function blurHashToDataURL(hash) {
  const width = 32;
  const height = 32;
  const pixels = decode(hash, width, height);
  const buffer = await sharp(Buffer.from(pixels), {
    raw: { width, height, channels: 4 },
  })
    .jpeg({ quality: 40 })
    .toBuffer();

  return `data:image/jpeg;base64,${buffer.toString("base64")}`;
}

const entries = [];

for (const relativePath of AMENITY_IMAGE_PATHS) {
  const absolutePath = path.join(publicDir, relativePath.slice(1));
  const blurHash = await encodeBlurHash(absolutePath);
  const blurDataURL = await blurHashToDataURL(blurHash);
  entries.push({ path: relativePath, blurHash, blurDataURL });
}

const file = `/** Auto-generated by scripts/generate-amenity-blurhash.mjs — do not edit by hand */
export type AmenityBlurEntry = {
  blurHash: string;
  blurDataURL: string;
};

export const AMENITY_BLUR_BY_PATH: Record<string, AmenityBlurEntry> = {
${entries
  .map(
    (entry) =>
      `  ${JSON.stringify(entry.path)}: { blurHash: ${JSON.stringify(entry.blurHash)}, blurDataURL: ${JSON.stringify(entry.blurDataURL)} },`,
  )
  .join("\n")}
};

export const AMENITY_BLUR_DATA_URLS: string[] = [
${entries.map((entry) => `  ${JSON.stringify(entry.blurDataURL)},`).join("\n")}
];
`;

writeFileSync(outFile, file, "utf8");
console.log(`Wrote ${entries.length} amenity blur placeholders → lib/amenityBlurHashes.ts`);
