/**
 * Generates blurhash + blurDataURL placeholders for home amenities + hero.
 * Run: npm run generate:amenity-blurhash
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { encode, decode } from "blurhash";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const publicDir = path.join(__dirname, "../public");
const amenityOutFile = path.join(__dirname, "../lib/amenityBlurHashes.ts");
const heroOutFile = path.join(__dirname, "../lib/heroBlurHash.ts");
const officeHeroOutFile = path.join(__dirname, "../lib/officeHeroBlurHash.ts");

const HERO_IMAGE_PATH = "/images/renders/render-34.jpg";
const OFFICE_HERO_IMAGE_PATH = "/images/drone/drone-6.jpg";

const AMENITY_IMAGE_PATHS = [
  "/images/renders/render-18.jpg",
  "/images/renders/render-25.jpg",
  "/images/renders/render-15.jpg",
  "/images/renders/render-12.jpg",
  "/images/mall/mall-12.jpg",
  "/images/mall/mall-5.jpg",
  "/images/mall/mall-1.jpg",
  "/images/drone/drone-2.jpg",
  "/images/renders/render-31.jpg",
  "/images/renders/render-3.jpg",
];

async function encodeBlurHash(imagePath) {
  const { data, info } = await sharp(imagePath)
    .rotate()
    .raw()
    .ensureAlpha()
    .resize(32, 32, { fit: "inside" })
    .toBuffer({ resolveWithObject: true });

  return encode(new Uint8ClampedArray(data), info.width, info.height, 4, 4);
}

async function blurHashToDataURL(hash) {
  const width = 32;
  const height = 32;
  const pixels = decode(hash, width, height);
  const buffer = await sharp(Buffer.from(pixels), {
    raw: { width, height, channels: 4 },
  })
    .jpeg({ quality: 40 })
    .toBuffer();

  return `data:image/jpeg;base64,${buffer.toString("base64")}`;
}

async function generateEntry(relativePath) {
  const absolutePath = path.join(publicDir, relativePath.slice(1));
  const blurHash = await encodeBlurHash(absolutePath);
  const blurDataURL = await blurHashToDataURL(blurHash);
  return { path: relativePath, blurHash, blurDataURL };
}

const entries = [];

for (const relativePath of AMENITY_IMAGE_PATHS) {
  entries.push(await generateEntry(relativePath));
}

const heroEntry = await generateEntry(HERO_IMAGE_PATH);
const officeHeroEntry = await generateEntry(OFFICE_HERO_IMAGE_PATH);

const amenityFile = `/** Auto-generated by scripts/generate-amenity-blurhash.mjs — do not edit by hand */
export type AmenityBlurEntry = {
  blurHash: string;
  blurDataURL: string;
};

export const AMENITY_BLUR_BY_PATH: Record<string, AmenityBlurEntry> = {
${entries
  .map(
    (entry) =>
      `  ${JSON.stringify(entry.path)}: { blurHash: ${JSON.stringify(entry.blurHash)}, blurDataURL: ${JSON.stringify(entry.blurDataURL)} },`,
  )
  .join("\n")}
};

export const AMENITY_BLUR_DATA_URLS: string[] = [
${entries.map((entry) => `  ${JSON.stringify(entry.blurDataURL)},`).join("\n")}
];
`;

writeFileSync(amenityOutFile, amenityFile, "utf8");

const heroFile = `/** Auto-generated by scripts/generate-amenity-blurhash.mjs — do not edit by hand */
export const HERO_BLUR_HASH = ${JSON.stringify(heroEntry.blurHash)};

export const HERO_BLUR_DATA_URL = ${JSON.stringify(heroEntry.blurDataURL)};
`;

writeFileSync(heroOutFile, heroFile, "utf8");

const officeHeroFile = `/** Auto-generated by scripts/generate-amenity-blurhash.mjs — do not edit by hand */
export const OFFICE_HERO_BLUR_HASH = ${JSON.stringify(officeHeroEntry.blurHash)};

export const OFFICE_HERO_BLUR_DATA_URL = ${JSON.stringify(officeHeroEntry.blurDataURL)};
`;

writeFileSync(officeHeroOutFile, officeHeroFile, "utf8");
console.log(`Wrote ${entries.length} amenity blur placeholders → lib/amenityBlurHashes.ts`);
console.log(`Wrote hero blur placeholder → lib/heroBlurHash.ts`);
console.log(`Wrote office hero blur placeholder → lib/officeHeroBlurHash.ts`);
